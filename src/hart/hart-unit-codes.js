export function getHartEngineeringUnit(unitCode, classification = null) {
  const code = Math.trunc(Number(unitCode));
  if (code >= 170 && code <= 219) {
    const expanded = HART_ENGINEERING_UNIT_EXPANSIONS[String(Math.trunc(Number(classification)))]?.[code];
    return expanded ? { ...expanded, classificationRequired: true } : null;
  }
  return HART_ENGINEERING_UNITS[code] ?? null;
}
